//! Regenerates `src/render/logo_glyphs/data.rs`, the sequence-logo letter
//! outlines, from the bundled DejaVu Sans Mono Bold. Run after changing the
//! font or the character set:
//!
//! ```sh
//! cargo run --example gen_logo_glyphs && cargo fmt
//! ```
//!
//! Baking the outlines into source keeps the logo free of a runtime font
//! parser and an embedded font. The
//! `logo_glyphs::tests::committed_table_matches_font` test fails if the
//! committed table drifts from the font.

#[path = "../src/render/logo_glyphs/extract.rs"]
mod extract;

use std::fmt::Write as _;

const FONT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/assets/fonts/DejaVuSansMono-Bold.ttf"
);
const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/src/render/logo_glyphs/data.rs"
);

fn main() {
    let font = std::fs::read(FONT).expect("cannot read DejaVuSansMono-Bold.ttf");
    let glyphs = extract::extract(&font);
    let mut s = String::new();
    s.push_str(
        "// Generated by `cargo run --example gen_logo_glyphs` from\n\
         // assets/fonts/DejaVuSansMono-Bold.ttf. Do not edit by hand.\n\n\
         use super::LogoGlyph;\n\n\
         /// Sorted by `ch` for binary search.\n\
         pub(crate) static LOGO_GLYPHS: &[LogoGlyph] = &[\n",
    );
    for g in &glyphs {
        let [x0, y0, x1, y1] = g.bbox;
        let _ = writeln!(
            s,
            "    LogoGlyph {{ ch: {:?}, path: {:?}, x_min: {x0:?}, y_min: {y0:?}, x_max: {x1:?}, y_max: {y1:?} }},",
            g.ch, g.path
        );
    }
    s.push_str("];\n");
    std::fs::write(OUT, s).expect("cannot write data.rs");
    println!("Wrote {} glyphs to {OUT}", glyphs.len());
}
